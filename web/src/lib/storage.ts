import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import type { S3Client } from "@aws-sdk/client-s3";

/**
 * Photo storage. Keys look like "u/<id>.webp" and "u/<id>-sm.webp". Listings store photos as "/media/<key>",
 * which stays the same whichever storage is used, so switching storage or adding a CDN needs no data change.
 *
 *   STORAGE_DRIVER=local (default): files under UPLOAD_DIR, served by /media/[...key].
 *   STORAGE_DRIVER=s3: Cloudflare R2 or AWS S3 (S3_BUCKET, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY,
 *     plus S3_ENDPOINT for R2 or S3_REGION for AWS). Served by /media/[...key] from the bucket, or straight
 *     from a public bucket / CDN when MEDIA_BASE_URL is set (faster, and takes load off the app).
 * Used by the web app and the worker, so no Next.js-only imports.
 */
const s3Enabled = () => process.env.STORAGE_DRIVER === "s3";
const root = () => resolve(process.cwd(), process.env.UPLOAD_DIR ?? "../.uploads");

/** Keys are generated by us, but validate anyway so a crafted key can never escape the folder or bucket prefix. */
export const KEY_PATTERN = /^u\/[a-z0-9]{10,40}(-sm)?\.webp$/;

function check(key: string) {
  if (!KEY_PATTERN.test(key)) throw new Error(`Invalid storage key: ${key}`);
}

let client: Promise<{ s3: S3Client; sdk: typeof import("@aws-sdk/client-s3") }> | null = null;
/** Loaded only when STORAGE_DRIVER=s3, so local development doesn't load the AWS SDK. */
function s3() {
  client ??= import("@aws-sdk/client-s3").then((sdk) => ({
    sdk,
    s3: new sdk.S3Client({
      region: process.env.S3_REGION ?? "auto", // R2 uses "auto"
      endpoint: process.env.S3_ENDPOINT || undefined, // e.g. https://<account>.r2.cloudflarestorage.com
      forcePathStyle: process.env.S3_FORCE_PATH_STYLE === "1", // MinIO and other self-hosted S3
      credentials: { accessKeyId: process.env.S3_ACCESS_KEY_ID ?? "", secretAccessKey: process.env.S3_SECRET_ACCESS_KEY ?? "" },
    }),
  }));
  return client;
}
const bucket = () => process.env.S3_BUCKET!;

export async function putObject(key: string, data: Buffer) {
  check(key);
  if (s3Enabled()) {
    const { s3: c, sdk } = await s3();
    await c.send(new sdk.PutObjectCommand({
      Bucket: bucket(), Key: key, Body: data, ContentType: "image/webp",
      // Keys never change content, so browsers and CDNs can keep them forever.
      CacheControl: "public, max-age=31536000, immutable",
    }));
    return;
  }
  const p = join(root(), key);
  await mkdir(dirname(p), { recursive: true });
  await writeFile(p, data);
}

export async function getObject(key: string): Promise<Buffer | null> {
  check(key);
  try {
    if (s3Enabled()) {
      const { s3: c, sdk } = await s3();
      const res = await c.send(new sdk.GetObjectCommand({ Bucket: bucket(), Key: key }));
      return res.Body ? Buffer.from(await res.Body.transformToByteArray()) : null;
    }
    return await readFile(join(root(), key));
  } catch {
    return null;
  }
}

export async function deleteObject(key: string) {
  check(key);
  try {
    if (s3Enabled()) {
      const { s3: c, sdk } = await s3();
      await c.send(new sdk.DeleteObjectCommand({ Bucket: bucket(), Key: key }));
    } else {
      await unlink(join(root(), key));
    }
  } catch {
    /* already gone */
  }
}

/** What listings store for a key: "/media/u/abc.webp". */
export function storedPath(key: string) {
  return `/media/${key}`;
}

/**
 * The URL a browser should load for a stored photo path. Sample photos ("/img/...") are unchanged;
 * uploaded ones go to MEDIA_BASE_URL when set, otherwise through /media.
 * size "sm" gives the 640 px card version of uploaded photos.
 */
export function photoUrl(stored: string, size: "lg" | "sm" = "lg") {
  let p = stored;
  if (size === "sm" && p.startsWith("/media/u/") && !p.endsWith("-sm.webp")) p = p.replace(/\.webp$/, "-sm.webp");
  const base = process.env.MEDIA_BASE_URL;
  return base && p.startsWith("/media/") ? base.replace(/\/$/, "") + p.slice("/media".length) : p;
}

/** Card-sized photo URL. */
export const smallVariant = (stored: string) => photoUrl(stored, "sm");
